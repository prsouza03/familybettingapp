const r = await fetch('https://www.bbc.co.uk/sport/football/scores-fixtures/2026-11-21');
const t = await r.text();
const m = t.match(/window\.__INITIAL_DATA__\s*=\s*("(?:[^"\\]|\\.)*")/);
const data = JSON.parse(JSON.parse(m[1]));
const key = Object.keys(data.data).find((k) => k.startsWith('sport-data-scores-fixtures'));
const groups = data.data[key].data.eventGroups;
console.log('GROUPS', groups.map((g) => `${g.displayLabel}[${(g.secondaryGroups || []).reduce((s, x) => s + (x.events || []).length, 0)}]`).join(' | '));
const g = groups.find((x) => /Scottish League Two/.test(x.displayLabel));
console.log('GROUPKEYS', Object.keys(g).join(','), 'SEC', Object.keys(g.secondaryGroups[0]).join(','), JSON.stringify(g.secondaryGroups[0].displayLabel));
console.log('EVENT', JSON.stringify(g.secondaryGroups[0].events[0]).slice(0, 3000));
const all = groups.flatMap((x) => x.secondaryGroups.flatMap((s) => s.events));
console.log('STATUSES', [...new Set(all.map((e) => JSON.stringify([e.status, e.statusComment?.value ?? e.statusComment, e.periodLabel?.value ?? e.periodLabel])))].join(' '));
